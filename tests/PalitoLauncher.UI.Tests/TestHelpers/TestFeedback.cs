namespace PalitoLauncher.UI.Tests.TestHelpers;

/// <summary>Encuestas y milestones de prueba (sin red ni Core de por medio).</summary>
internal static class TestFeedback
{
    /// <summary>
    /// Encuesta con todos los tipos: overall (Rating, obligatoria), again (Choice, obligatoria), difficulty (Scale 1..5 con
    /// etiquetas), issues (Multi con «Ninguno»), best (Text) e improve (Text, máx. 50).
    /// </summary>
    public static SurveyDefinition Survey(string? webhook = null) => new()
    {
        Id = "test-survey",
        Title = "Tu opinión sobre Coop2D",
        Intro = "Son solo unas preguntas.",
        AskAfterSession = true,
        MinSessionMinutes = 5,
        MinHoursBetweenPrompts = 12,
        DiscordWebhookUrl = webhook,
        Questions = new List<SurveyQuestion>
        {
            new() { Id = "overall", Type = SurveyQuestionType.Rating, Text = "En general, ¿qué tal la partida?", Required = true },
            new()
            {
                Id = "again", Type = SurveyQuestionType.Choice, Text = "¿Te apetece volver a jugar?", Required = true,
                Options = new List<string> { "Sí, otra partida ya", "Sí, otro día", "No mucho" },
            },
            new()
            {
                Id = "difficulty", Type = SurveyQuestionType.Scale, Text = "¿Qué tal la dificultad?", Min = 1, Max = 5,
                MinLabel = "Muy fácil", MaxLabel = "Muy difícil", Hint = "1 = muy fácil, 5 = muy difícil",
            },
            new()
            {
                Id = "issues", Type = SurveyQuestionType.Multi, Text = "¿Tuviste algún problema?",
                Options = new List<string> { "Lag o desconexiones", "El juego se cerró", "Fallos visuales", "Ninguno" },
            },
            new() { Id = "best", Type = SurveyQuestionType.Text, Text = "¿Qué fue lo mejor?", Placeholder = "Cuéntanos…" },
            new() { Id = "improve", Type = SurveyQuestionType.Text, Text = "¿Qué cambiarías?", MaxLength = 50 },
        },
    };

    public static MilestoneInfo Milestone(int number, string title, int open, int closed, bool isClosed = false, string? description = null)
        => new()
        {
            Number = number,
            Title = title,
            Description = description,
            IsClosed = isClosed,
            OpenIssues = open,
            ClosedIssues = closed,
            HtmlUrl = $"https://github.com/JJJP-Dev/Coop2D/milestone/{number}",
            UpdatedAt = TestReleases.BaseDate,
        };

    /// <summary>Roadmap parecido al real: Pre 1 y Pre 2 en curso, Pre 3 siguiente, 0.1 planificado, 1.0 lanzamiento.</summary>
    public static IReadOnlyList<MilestoneInfo> Milestones() => new[]
    {
        Milestone(1, "Pre 1 · Tech prototype", open: 1, closed: 26,
            description: "Pre-producción.\n\nPregunta: ¿pueden 2-4 jugadores conectarse por internet y moverse?\n\nHecho cuando: la prueba remota va fluida.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"),
        Milestone(2, "Pre 2 · Gameplay prototype", open: 11, closed: 14,
            description: "Pre-producción.\n\nPregunta: ¿es divertido combinar elementos con un compañero?\n\nReglas: arte provisional."),
        Milestone(3, "Pre 3 · First playable", open: 24, closed: 0, description: "Pre-producción.\n\nPregunta: ¿una partida entera tiene ritmo?"),
        Milestone(5, "0.1 · Runs and rooms", open: 5, closed: 0, description: "Producción.\n\nObjetivo: partidas formadas por salas."),
        Milestone(14, "1.0 · Launch", open: 0, closed: 0),
    };

    public static MilestoneFetchResult Result(IReadOnlyList<MilestoneInfo>? milestones = null,
        ReleaseFetchSource source = ReleaseFetchSource.Network) => new()
    {
        Milestones = milestones ?? Milestones(),
        Source = source,
        FetchedAt = DateTimeOffset.UtcNow,
        Warning = source == ReleaseFetchSource.OfflineCache ? "Sin conexión con GitHub. Mostrando datos guardados." : null,
    };
}
